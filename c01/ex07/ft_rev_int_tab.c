void	ft_rev_int_tab(int *tab, int size)
{
	int	i;
	int	z;
	int	c;

	i = 0;
	z = size / 2;
	while (i < z)
	{
		c = tab[i];
		tab[i] = tab[size - i - 1];
		tab[size - i - 1] = c;
		i++;
	}
}
