void	ft_sort_int_tab(int *tab, int size)
{
	int	i;
	int	z;
	int	c;

	i = 0;
	while (i < size)
	{
		z = i + 1;
		while (z < size)
		{
			if (tab[i] < tab[z])
			{
				c = tab[z];
				tab[z] = tab[i];
				tab[i] = c;
			}
			z++;
		}
		i++;
	}
}
