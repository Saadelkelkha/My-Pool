#include <stdlib.h>

char	*ft_strdup(char *src)
{
	char	*c;
	int		i;

	i = 0;
	while (src[i])
		i++;
	c = malloc(i + 1);
	if (!c)
		return (0);
	i = 0;
	while (src[i])
	{
		*(c + i) = src[i];
		i++;
	}
	*(c + i) = src[i];
	return (c);
}
