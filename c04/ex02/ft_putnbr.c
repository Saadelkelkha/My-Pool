#include <unistd.h>

void	ft_putnbr(int nb)
{
	long	n;
	char	*s;

	n = nb;
	s = "0123456789";
	if (n < 0)
	{
		write(1, "-", 1);
		n = -n;
	}
	if (n >= 10)
	{
		ft_putnbr(n / 10);
		n = n % 10;
	}
	write(1, &s[n], 1);
}
