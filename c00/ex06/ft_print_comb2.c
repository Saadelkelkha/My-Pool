#include <unistd.h>

void	ft_print_comb2(void)
{
	int		a;
	int		b;
	char	*s;

	s = "0123456789";
	a = 0;
	while (a < 99)
	{
		b = a + 1;
		while (b < 100)
		{
			write(1, &s[a / 10], 1);
			write(1, &s[a % 10], 1);
			write(1, " ", 1);
			write(1, &s[b / 10], 1);
			write(1, &s[b % 10], 1);
			if (!(a == 98 && b == 99))
			{
				write(1, ", ", 2);
			}
			b++;
		}
		a++;
	}
}
