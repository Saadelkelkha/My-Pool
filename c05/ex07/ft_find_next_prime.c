int	ft_find_next_prime(int nb)
{
	int	n;
	int	j;

	n = nb + 1;
	while (n > nb)
	{
		j = 2;
		while (j < n && n % j != 0 && n > 1)
			j++;
		if (j == n)
			break ;
		else
			n++;
	}
	return (n);
}
